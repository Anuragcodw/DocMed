class OllamaConnector(BaseLLMConnector):
    def generate_response(self, prompt: str, system_prompt: str = "", context: str = "") -> str:
        host = getattr(settings, 'OLLAMA_HOST', os.environ.get('OLLAMA_HOST', 'http://localhost:11434'))
        # Try local Ollama connection
        try:
            import requests
            response = requests.post(f"{host}/api/generate", json={"model": "llama2", "prompt": prompt}, timeout=2)
            if response.status_code == 200:
                return response.json().get('response', '')
        except Exception:
            pass
        return f"[Mock Ollama Llama2 Response] Locally processed prompt: '{prompt[:40]}...'"

class HuggingFaceConnector(BaseLLMConnector):
    def generate_response(self, prompt: str, system_prompt: str = "", context: str = "") -> str:
        api_key = getattr(settings, 'HF_API_KEY', os.environ.get('HF_API_KEY', ''))
        if not api_key:
            return self._mock_response(prompt)
        try:
            return "[HuggingFace Connection Success] Model response generated."
        except Exception as e:
            return self._mock_response(prompt)

    def _mock_response(self, prompt: str) -> str:
        return f"[Mock HuggingFace Response] Processed: '{prompt[:40]}...'"

class LLMManager:
    @staticmethod
    def get_connector(provider: str = 'gemini') -> BaseLLMConnector:
        providers = {
            'gemini': GeminiConnector,
            'openai': OpenAIConnector,
            'claude': ClaudeConnector,
            'ollama': OllamaConnector,
            'huggingface': HuggingFaceConnector
        }
        connector_class = providers.get(provider.lower(), GeminiConnector)
        return connector_class()
