import os
import logging
from django.conf import settings

logger = logging.getLogger(__name__)

class BaseLLMConnector:
    def generate_response(self, prompt: str, system_prompt: str = "", context: str = "") -> str:
        raise NotImplementedError("Subclasses must implement generate_response")

class GeminiConnector(BaseLLMConnector):
    def generate_response(self, prompt: str, system_prompt: str = "", context: str = "") -> str:
        try:
            from ai.services.gemini import GeminiClient
            client = GeminiClient()
            return client.generate_content(prompt, context=context, system_instruction=system_prompt)
        except Exception as e:
            logger.error(f"Gemini generation error: {e}")
            return self._mock_response(prompt)

    def _mock_response(self, prompt: str) -> str:
        return f"[Mock Gemini Response] Thank you for your inquiry. This is a placeholder AI response for prompt: '{prompt[:40]}...'"

